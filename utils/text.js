export function normalizeWhitespace(value) {
  // Убираем пробелы по краям строки.
  // Затем \s+ находит один или несколько подряд идущих whitespace-символов,
  // а флаг g применяет замену ко всей строке, а не только к первому совпадению.
  return value.trim().replace(/\s+/g, ' ');
}

export function toSlug(value) {
  // Сначала применяем ту же нормализацию пробелов, что и для отображаемого title.
  return (
    normalizeWhitespace(value)
      // Slug не зависит от регистра.
      .toLowerCase()
      // NFKD раскладывает составные Unicode-символы на базовый символ и знак.
      .normalize('NFKD')
      // \p{M} — Unicode-категория combining marks; u включает Unicode-режим,
      // g удаляет все найденные диакритические знаки.
      .replace(/\p{M}/gu, '')
      // \p{L} — любая Unicode-буква, \p{N} — любая Unicode-цифра.
      // Класс с ^ означает «все остальные символы», а + объединяет их группы.
      // Каждая такая группа превращается в один дефис.
      .replace(/[^\p{L}\p{N}]+/gu, '-')
      // Удаляем случайные дефисы в начале и конце результата:
      // ^- означает дефис в начале, а -$ — дефис в конце.
      .replace(/^-|-$/g, '')
  );
}
